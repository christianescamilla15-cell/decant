-- Destino de la carga histórica por mes (S3 paso 3, ADR 0013). Lo corre `python -m corte.runbook preparar`.
--
-- Esquema `legado`: las 7 tablas del legado copiadas fila por fila CON sus ids y sus valores CRUDOS: tipos que
-- conservan el valor exacto (char(n) con su relleno, los centinelas «NA» y 0 tal cual, las horas locales sin zona,
-- los decimales con su escala). Los parches del ADR 0007 y las horas a instantes (ADR 0008) se aplican de `legado` al
-- TO-BE, como ya los aplica y mide S2: aquí la huella de cada mes tiene que ser IGUAL en origen y destino.
-- Los ÚNICOS índices únicos son los del legado (sus llaves primarias): el runbook compara los dos catálogos antes de
-- ensayar y de aplicar. Sin llaves foráneas mientras se carga: un mes referencia filas de meses anteriores (los
-- re-registros y las liquidaciones de órdenes viejas). Se agregan, validando, en el cierre.
--
-- Esquema `corte`: el registro del corte. Los dos roles separan los verbos: `aplicar` sólo INSERTA en las tablas del
-- legado (además de setval y del consumible), `reversa` sólo BORRA. Ninguno puede tocar el punto de no retorno.

CREATE SCHEMA legado;
CREATE SCHEMA corte;

CREATE TABLE legado.moneda (
    codigo      char(3)       NOT NULL CONSTRAINT pk_moneda PRIMARY KEY,
    numerico    char(3)       NOT NULL,
    nombre      varchar(60)   NOT NULL,
    decimales   smallint      NOT NULL,
    activa      boolean       NOT NULL
);

CREATE TABLE legado.folio (
    serie       varchar(10)   NOT NULL CONSTRAINT pk_folio PRIMARY KEY,
    siguiente   integer       NOT NULL,
    actualizado timestamp     NULL          -- se copia en el cierre: hasta ahí es NULL
);

CREATE TABLE legado.operacion (
    id                      integer NOT NULL GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME legado.operacion_id_seq)
                            CONSTRAINT pk_operacion PRIMARY KEY,
    folio                   varchar(20)    NOT NULL,
    fecha_operacion         timestamp      NOT NULL,
    sucursal                char(4)        NOT NULL,
    canal                   varchar(10)    NOT NULL,
    cliente                 varchar(120)   NOT NULL,
    cuenta_clabe            varchar(18)    NOT NULL,  -- con su centinela «NA»
    tipo                    char(1)        NOT NULL,
    moneda                  char(3)        NOT NULL,
    monto_divisa            numeric(18, 2) NOT NULL,
    tipo_cambio             numeric(18, 6) NOT NULL,
    tipo_cambio_referencia  numeric(18, 6) NOT NULL,  -- con su centinela 0
    monto_mxn               numeric(18, 2) NOT NULL,
    estatus                 varchar(12)    NOT NULL
);

CREATE TABLE legado.orden_pago (
    id                   integer NOT NULL GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME legado.orden_pago_id_seq)
                         CONSTRAINT pk_orden_pago PRIMARY KEY,
    operacion_id         integer        NOT NULL,
    folio                varchar(20)    NOT NULL,
    uetr                 char(36)       NOT NULL,
    referencia_mt103     varchar(16)    NOT NULL,
    fecha_registro       timestamp      NOT NULL,
    fecha_envio          timestamp      NOT NULL,
    fecha_valor          date           NOT NULL,
    bic_corresponsal     char(11)       NOT NULL,
    bic_intermediario    char(11)       NOT NULL,     -- con su centinela «NA»
    beneficiario         varchar(120)   NOT NULL,
    cuenta_beneficiario  varchar(34)    NOT NULL,
    moneda               char(3)        NOT NULL,
    monto                numeric(18, 2) NOT NULL,
    gastos               char(3)        NOT NULL,
    codigo_proposito     char(4)        NULL,
    estatus              varchar(12)    NOT NULL,
    horas_liquidacion    numeric(9, 2)  NULL
);

CREATE TABLE legado.partida_solicitada (
    id          integer NOT NULL GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME legado.partida_solicitada_id_seq)
                CONSTRAINT pk_partida_solicitada PRIMARY KEY,
    orden_id    integer        NOT NULL,
    renglon     smallint       NOT NULL,
    concepto    varchar(24)    NOT NULL,
    moneda      char(3)        NOT NULL,
    monto       numeric(18, 2) NOT NULL,
    fecha_hora  timestamp      NOT NULL,
    referencia  varchar(35)    NOT NULL
);

CREATE TABLE legado.partida_liquidada (
    id          integer NOT NULL GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME legado.partida_liquidada_id_seq)
                CONSTRAINT pk_partida_liquidada PRIMARY KEY,
    orden_id    integer        NOT NULL,
    renglon     smallint       NOT NULL,
    concepto    varchar(24)    NOT NULL,
    moneda      char(3)        NOT NULL,
    monto       numeric(18, 2) NOT NULL,
    fecha_hora  timestamp      NOT NULL,
    referencia  varchar(35)    NOT NULL
);

CREATE TABLE legado.bitacora (
    id                bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME legado.bitacora_id_seq)
                      CONSTRAINT pk_bitacora PRIMARY KEY,
    tabla             varchar(128)   NOT NULL,
    llave             integer        NOT NULL,
    accion            char(1)        NOT NULL,
    estatus_anterior  varchar(12)    NULL,
    estatus_nuevo     varchar(12)    NULL,
    usuario           varchar(128)   NOT NULL,
    fecha             timestamp      NOT NULL
);

-- ── registro del corte ──────────────────────────────────────────────────────────────────────────────────────────

-- Cada mes: la reversa y la huella previa se GUARDAN antes de insertar nada (estado «reversa_generada»).
CREATE TABLE corte.carga_mes (
    id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    mes           char(7)      NOT NULL,
    plan_sha      char(64)     NOT NULL,
    estado        text         NOT NULL CHECK (estado IN ('reversa_generada', 'aplicado', 'revertido', 'fallido')),
    rangos        jsonb        NOT NULL,
    reversa       jsonb        NOT NULL,
    huella_previa jsonb        NOT NULL,
    huella_mes    jsonb        NULL,
    carga_txid    bigint       NULL,
    generada_en   timestamptz  NOT NULL DEFAULT clock_timestamp(),
    aplicada_en   timestamptz  NULL,
    revertida_en  timestamptz  NULL,
    detalle       text         NULL
);

-- Lo que se ensayó (en una transacción revertida sobre esta misma base): `aplicar` exige un ensayo verde del mismo
-- mes, con el mismo plan y sobre la misma huella previa.
CREATE TABLE corte.ensayo (
    id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    mes           char(7)      NOT NULL,
    plan_sha      char(64)     NOT NULL,
    huella_previa jsonb        NOT NULL,
    verde         boolean      NOT NULL,
    resultado     jsonb        NOT NULL,
    instante      timestamptz  NOT NULL DEFAULT clock_timestamp()
);

-- Automatismos del TO-BE (los nombres son las banderas de Decant.Application.Banderas). Precargados APAGADOS: el día
-- del corte sólo se encienden. `aplicar` se niega si alguno está encendido.
CREATE TABLE corte.interruptor (
    nombre       text         PRIMARY KEY,
    encendido    boolean      NOT NULL DEFAULT false,
    cambiado_en  timestamptz  NOT NULL DEFAULT clock_timestamp()
);
INSERT INTO corte.interruptor (nombre) VALUES ('VencerAutomatico'), ('ConciliarAutomatico'), ('NotificarCorresponsal');

-- Bitácora de ACCIONES de negocio del TO-BE: lo único que dice que una fila «ya se trabajó». Las escrituras
-- informativas del sistema (marcas, validaciones) cambian el token de concurrencia y no pasan por aquí.
CREATE TABLE corte.accion_negocio (
    id        bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    tabla     text         NOT NULL,
    fila      bigint       NOT NULL,
    accion    text         NOT NULL,
    usuario   text         NOT NULL DEFAULT current_user,
    instante  timestamptz  NOT NULL DEFAULT clock_timestamp()
);

-- Avisos al exterior (al corresponsal, por correo): el otro evento que cruza el punto de no retorno.
CREATE TABLE corte.aviso_exterior (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    destino     text         NOT NULL,
    referencia  text         NOT NULL,
    instante    timestamptz  NOT NULL DEFAULT clock_timestamp()
);

-- El punto de no retorno: UN renglón, lo escribe el sistema (los disparadores de abajo) con la PRIMERA acción de
-- negocio o el PRIMER aviso. Desde ahí `reversa` se niega.
CREATE TABLE corte.no_retorno (
    unico       boolean      PRIMARY KEY DEFAULT true CHECK (unico),
    instante    timestamptz  NOT NULL,
    motivo      text         NOT NULL,
    referencia  text         NOT NULL
);

CREATE FUNCTION corte.registrar_no_retorno() RETURNS trigger
    LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, corte AS $$
BEGIN
    IF TG_TABLE_NAME = 'accion_negocio' THEN
        INSERT INTO corte.no_retorno (instante, motivo, referencia)
        VALUES (NEW.instante, 'primera escritura de negocio aceptada en el TO-BE',
                format('%s sobre %s #%s (accion_negocio %s)', NEW.accion, NEW.tabla, NEW.fila, NEW.id))
        ON CONFLICT (unico) DO NOTHING;
    ELSE
        INSERT INTO corte.no_retorno (instante, motivo, referencia)
        VALUES (NEW.instante, 'primer aviso al exterior',
                format('%s → %s (aviso_exterior %s)', NEW.referencia, NEW.destino, NEW.id))
        ON CONFLICT (unico) DO NOTHING;
    END IF;
    RETURN NULL;
END
$$;

CREATE TRIGGER tr_no_retorno_por_accion AFTER INSERT ON corte.accion_negocio
    FOR EACH ROW EXECUTE FUNCTION corte.registrar_no_retorno();
CREATE TRIGGER tr_no_retorno_por_aviso AFTER INSERT ON corte.aviso_exterior
    FOR EACH ROW EXECUTE FUNCTION corte.registrar_no_retorno();

-- ── permisos de cada verbo ──────────────────────────────────────────────────────────────────────────────────────
-- Los roles son del servidor (puede haber más de una base de corte): se crean una vez.
DO $$
BEGIN
    CREATE ROLE decant_corte_aplica NOLOGIN;
EXCEPTION WHEN duplicate_object THEN NULL;
END
$$;
DO $$
BEGIN
    CREATE ROLE decant_corte_revierte NOLOGIN;
EXCEPTION WHEN duplicate_object THEN NULL;
END
$$;

GRANT USAGE ON SCHEMA legado, corte TO decant_corte_aplica, decant_corte_revierte;
GRANT SELECT ON ALL TABLES IN SCHEMA legado, corte TO decant_corte_aplica, decant_corte_revierte;
-- aplicar: sólo INSERT en las tablas con identidad; el consumible y las secuencias se mueven (y la reversa los regresa)
GRANT INSERT ON legado.operacion, legado.orden_pago, legado.partida_solicitada, legado.partida_liquidada,
    legado.bitacora TO decant_corte_aplica;
-- reversa: sólo DELETE en esas mismas tablas
GRANT DELETE ON legado.operacion, legado.orden_pago, legado.partida_solicitada, legado.partida_liquidada,
    legado.bitacora TO decant_corte_revierte;
GRANT UPDATE (siguiente) ON legado.folio TO decant_corte_aplica, decant_corte_revierte;
GRANT USAGE, SELECT, UPDATE ON ALL SEQUENCES IN SCHEMA legado TO decant_corte_aplica, decant_corte_revierte;
-- el registro: lo escriben los dos; el punto de no retorno, ninguno
GRANT INSERT, UPDATE ON corte.carga_mes, corte.ensayo TO decant_corte_aplica, decant_corte_revierte;
